#!/usr/bin/env python3
"""Embed the native MSL source for Metal's runtime library compiler.

This only checks source embedding; Apple shader compilation is a separate CI
step using xcrun metal. It does not translate GLSL or require a Vulkan runtime.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "source/build/src/metal_polymost.metal"
DESTINATION = ROOT / "source/build/src/metal_shaders.h"
DELIMITER = "NBLOOD_METAL"


def generated_header() -> bytes:
    source = SOURCE.read_text(encoding="utf-8")
    if f'){DELIMITER}"' in source:
        raise ValueError("Metal source contains the raw-string delimiter")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    return (
        "// Generated by platform/ci/embed-metal-shaders.py; edit metal_polymost.metal.\n"
        "// SPDX-License-Identifier: GPL-2.0-only\n"
        f"// Source SHA-256: {digest}\n"
        "#pragma once\n"
        f'static constexpr char kMetalShaderSource[] = R"{DELIMITER}(\n'
        f"{source}"
        f'){DELIMITER}";\n'
    ).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the embedded source is stale")
    args = parser.parse_args()
    generated = generated_header()
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_bytes() != generated:
            parser.exit(1, f"{DESTINATION} is stale; run {Path(__file__).name}.\n")
        print("Embedded Metal source matches metal_polymost.metal.")
    else:
        DESTINATION.write_bytes(generated)
        print(f"Updated {DESTINATION.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
