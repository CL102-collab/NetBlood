#!/usr/bin/env python3
"""Compile and validate Vulkan shaders, then embed reproducible SPIR-V words.

Requires glslangValidator and spirv-val on PATH. Run with --check to verify that
the checked-in header matches the shader sources and the installed compiler.
"""
# SPDX-License-Identifier: GPL-2.0-only
# Copyright (C) 2026 NBlood contributors.

import argparse
import pathlib
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without writing")
    args = parser.parse_args()
    root = pathlib.Path(__file__).resolve().parents[2]
    source = root / "source/build/src"
    with tempfile.TemporaryDirectory(prefix="netblood-vulkan-shaders-") as temporary:
        for program in ("vulkan_polymost", "ambient_occlusion_vk"):
            destination = source / (program + "_spv.h")
            description = ("// Derived from NBlood's Polymost1 shaders. See vulkan_polymost.vert/.frag."
                           if program == "vulkan_polymost" else
                           "// Native AO wrapper around the shared ambient_occlusion.glsl algorithm.")
            lines = [
                "// SPDX-License-Identifier: GPL-2.0-only",
                "// Generated by tests/vulkan/generate-shaders.py; edit the GLSL sources.",
                description,
                "#pragma once",
                "#include <stdint.h>",
                "",
            ]
            for stage in ("vert", "frag"):
                binary = pathlib.Path(temporary) / (program + "." + stage + ".spv")
                subprocess.run(
                    ["glslangValidator", "-V", "--target-env", "vulkan1.0", "-g0",
                     "-o", str(binary), program + "." + stage],
                    cwd=source, check=True,
                )
                subprocess.run(["spirv-val", "--target-env", "vulkan1.0", str(binary)], check=True)
                raw = binary.read_bytes()
                words = struct.unpack("<" + "I" * (len(raw) // 4), raw)
                if not words or words[0] != 0x07230203:
                    raise RuntimeError("Compiler did not produce a SPIR-V module")
                lines += ["static const uint32_t " + program + "_" + stage + "_spv[] =", "{"]
                for offset in range(0, len(words), 8):
                    lines.append("    " + ", ".join(f"0x{word:08x}u" for word in words[offset:offset + 8]) + ",")
                lines += ["};", ""]
            generated = "\n".join(lines)
            if args.check:
                if not destination.exists() or destination.read_text() != generated:
                    parser.exit(1, f"{destination} is stale; regenerate the shader header.\n")
            else:
                destination.write_text(generated)
                print(f"Wrote {destination.relative_to(root)}")
    if args.check:
        print("Embedded Vulkan shaders match the GLSL sources.")


if __name__ == "__main__":
    main()
